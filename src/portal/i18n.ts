export type Lang = 'nl' | 'en' | 'de'
export const LANGS: { id: Lang; label: string }[] = [
  { id: 'nl', label: 'NL' },
  { id: 'en', label: 'EN' },
  { id: 'de', label: 'DE' },
]
export const asLang = (l: unknown): Lang => (l === 'en' || l === 'de' ? l : 'nl')

const KEY = 'vonstruct.lang'
/** Laatst gekozen taal in deze browser; anders de taal van de browser. */
export const storedLang = (): Lang => {
  try {
    const s = localStorage.getItem(KEY)
    if (s) return asLang(s)
  } catch { /* geen opslag */ }
  const n = (navigator.language || 'nl').slice(0, 2)
  return n === 'de' ? 'de' : n === 'en' ? 'en' : 'nl'
}
export const storeLang = (l: Lang) => { try { localStorage.setItem(KEY, l) } catch { /* geen opslag */ } }

